namespace EmployeeOperationsMvc.Middleware
{
    public class ConditionalRequestMiddleware
    {
        private readonly RequestDelegate _next;
        private readonly ILogger<ConditionalRequestMiddleware> _logger;

        public ConditionalRequestMiddleware(
            RequestDelegate next,
            ILogger<ConditionalRequestMiddleware> logger)
        {
            _next = next;
            _logger = logger;
        }

        public async Task InvokeAsync(HttpContext context)
        {
            string path = context.Request.Path.Value ?? string.Empty;

            // Condition 1: Return a response for a specific path.
            if (path.Equals(
                "/middleware-demo/early-response",
                StringComparison.OrdinalIgnoreCase))
            {
                _logger.LogInformation(
                    "Conditional middleware handled {Path} directly.",
                    path);

                context.Response.StatusCode = StatusCodes.Status200OK;
                context.Response.ContentType = "text/plain; charset=utf-8";

                await context.Response.WriteAsync(
                    "This response was generated by conditional " +
                    "middleware. No MVC controller was executed.");

                return;
            }

            // Condition 2: Intercept only when mode=early.
            if (path.Equals(
                    "/middleware-demo/conditional",
                    StringComparison.OrdinalIgnoreCase)
                && string.Equals(
                    context.Request.Query["mode"].ToString(),
                    "early",
                    StringComparison.OrdinalIgnoreCase))
            {
                context.Response.StatusCode = StatusCodes.Status200OK;
                context.Response.ContentType = "text/plain; charset=utf-8";

                await context.Response.WriteAsync(
                    "The query parameter triggered an early response.");

                return;
            }

            // Neither condition matched. Continue to MVC.
            await _next(context);
        }
    }
}
